"""行程內的小快取：給「幾乎不會變、但每一頁都要查」的那幾張小表

## 為什麼要有它

首頁的程式碼只跑幾毫秒，卻要等 18 趟資料庫往返（Supabase 在雪梨，一趟算 100ms 就是快 2 秒，
而那些全部是在等）。其中一半是在查「這個月大概不會變」的東西：系統設定、首頁磁磚的可見度與順序、
快捷連結、經文底圖。`Procfile` 用 `--threads 8`（一個行程、八條執行緒），所以這份快取全部請求共用。

## ★★ 這個模組最大的風險不是「快取失效」，是「畫面說的是假的」

後台改完、回前台看、還是舊的 —— 使用者看到的是「我剛剛那一下沒有存到」，他會再存一次、再重整一次，
然後來問，而畫面上完全正常。所以：

1. **寫入端一定要 `bust()`** —— 那才是「改完立刻看得到」的唯一保證（`tests/test_cache_is_busted.py`
   會掃：每一個被快取的 key 都必須有寫入端清它）
2. TTL 只是最後一道防線（漏掉 `bust()` 的最多舊 TTL 秒，不會永遠是舊的）

★ 只快取**整張表的小清單**，不快取跟使用者有關的東西。「這個人報了什麼」快取起來的話，
  代價是下一個人看到別人的資料 —— 那不是效能問題，那是事故。

★ 多 worker 的話每個 worker 各有一份：後果是「有時看到新的、有時看到舊的」，最多 TTL 秒。
  （目前是 `--workers=1`，改之前要重新評估。）

# shortcut: 成熟版另有 `warm()`（排程定時預先算好，讓「一小時才一個人開首頁」的流量也吃得到快取）；
#   這個 repo 沒有排程（`tasks.py`），所以第一個人會付冷快取的代價。搬了排程再補。
"""
import time

#  key → (放到什麼時候, 值)
_store = {}

#  ★ **只有這一個數字**。呼叫端不要各自寫一個 —— 寫死在好幾個地方的話，
#    以後調整只會改到其中幾個，而另外幾個安靜地維持舊值（有測試在掃）。
DEFAULT_TTL = 600


def get(key, build):
    """快取裡有就拿，沒有就叫 `build()` 算一次。

    ★ `build()` 丟例外時**不要快取** —— 把一次失敗記住的話，資料庫抖一下
      就會讓首頁少一塊東西整整 TTL 那麼久。例外直接往上傳，不寫進 `_store`。
    """
    hit = _store.get(key)
    now = time.time()
    if hit and hit[0] > now:
        return hit[1]
    value = build()
    _store[key] = (now + DEFAULT_TTL, value)
    return value


def bust(*keys):
    """把這幾個 key 清掉 —— **寫入端一定要叫**。"""
    for k in keys:
        _store.pop(k, None)


def clear():
    """全部清掉（測試用）。"""
    _store.clear()
