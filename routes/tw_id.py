"""身分證字號 / 居留證號：格式與檢查碼

保險名冊要身分證字號。**打錯一個字的後果是那個人根本沒被保到** ——
而且不會有任何徵兆，要出事那一刻才會發現。

所以這裡不只檢查格式，還算檢查碼。身分證字號本身就內建一位檢查碼，
隨手打錯一個數字有九成會被算出來 —— 這是少數「能在輸入當下就擋掉」
的錯誤，不用它太可惜。

## 三種格式

  本國國民          A123456789      第 2 碼 1（男）或 2（女）
  新式外來人口統一證號 A812345678     第 2 碼 8 或 9（2021 年起）
  舊式居留證         AB12345678      第 2 碼是英文字母 A–D

前兩種的檢查碼算法完全一樣。舊式的差別只在「第 2 碼要先換成數字」。

## 只做驗證

不做遮蔽 —— 名冊只有管理員看得到（使用者確認過），多一層遮蔽只是多一個
要按的按鈕。真的需要時再加。

## 一律轉大寫、去空白，但不猜

使用者會打小寫、會在中間打空格。這些是排版差異，轉一下就好。
但格式不對就是不對 —— 不要試著「修好」它，一個被系統修過的證號
看起來跟正確的一模一樣。
"""
import re

# 英文字母對應的兩位數字（內政部的對照表，不是規律的 —— I/O/W/X/Y/Z
# 那幾個特別跳號，不要「順手改成連續」）
_LETTER = {
    'A': 10, 'B': 11, 'C': 12, 'D': 13, 'E': 14, 'F': 15, 'G': 16, 'H': 17,
    'I': 34, 'J': 18, 'K': 19, 'L': 20, 'M': 21, 'N': 22, 'O': 35, 'P': 23,
    'Q': 24, 'R': 25, 'S': 26, 'T': 27, 'U': 28, 'V': 29, 'W': 32, 'X': 30,
    'Y': 31, 'Z': 33,
}

# 第 2 碼：1/2 本國，8/9 新式外來人口，A–D 舊式居留證
_NATIONAL = re.compile(r'^[A-Z][1289]\d{8}$')
_LEGACY_ARC = re.compile(r'^[A-Z][A-D]\d{8}$')

# 權重：首字母拆成兩位（權重 1、9），其後 8 碼權重 8…1，最後檢查碼權重 1
_WEIGHTS = (8, 7, 6, 5, 4, 3, 2, 1)


def normalize(value):
    """去空白、轉大寫。認不出來也照樣回傳 —— 判斷交給 is_valid。"""
    if value is None:
        return ''
    return re.sub(r'\s+', '', str(value)).upper()


def is_valid(value):
    """格式與檢查碼都對才算數。"""
    s = normalize(value)
    if _NATIONAL.match(s):
        second = int(s[1])
    elif _LEGACY_ARC.match(s):
        # 舊式居留證：第 2 碼的英文字母取它對照數字的個位數
        second = _LETTER[s[1]] % 10
    else:
        return False

    first = _LETTER.get(s[0])
    if first is None:
        return False

    total = first // 10 + (first % 10) * 9 + second * _WEIGHTS[0]
    for i, w in enumerate(_WEIGHTS[1:], start=2):
        total += int(s[i]) * w
    total += int(s[9])          # 檢查碼本身，權重 1
    return total % 10 == 0


def mask(value):
    """遮蔽後的身分證字號：`A123456789` → `A12****789`。

    ## 為什麼要遮

    報名憑證／查詢頁會把填過的答案列回去給報名者看。但**他本來就知道
    自己的身分證字號** —— 印全串對他沒有任何幫助，只是把外洩的代價
    放到最大。

    而那一頁是「知道姓名＋電話就打得開」的：鑰匙再硬，也沒有理由
    讓門後面放著一整串證號。

    ★ 這一條跟「查詢的驗證因子要多強」是**兩件獨立的事**，不要混在一起
      討論。鑰匙硬不硬決定「多難打開」，遮不遮決定「打開之後看到什麼」——
      後者是我們完全控制得了的那一半。

    ★ 後台名冊和 Excel **不遮**：保險公司要完整號碼，那是它存在的理由。
      遮的只有報名者自己看的畫面。

    認不出格式的一律原樣回傳（不要自作聰明去切一個看起來像遮蔽的東西）。
    """
    s = normalize(value)
    if len(s) != 10:
        return str(value or '')
    return s[:3] + '****' + s[7:]
