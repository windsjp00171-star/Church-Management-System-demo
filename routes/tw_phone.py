"""電話遮蔽：`0912345678` → `0912***678`

使用者定的：
> 「我們不是在後台名單頁面有把每個人的身分證字號做遮罩嗎 電話也要喔~
>   那也是敏感資訊」

跟身分證字號同一個理由：**名單頁是開在人面前的** —— 收費桌、簽到台、
有人站在旁邊等，還會被截圖傳出去。而在那一頁沒有人需要讀完整的號碼；
真的要打電話時點一下就看得到。

## ★ 遮蔽的判斷方向，跟「查詢」剛好相反

`routes/reg_manage._phones_of` 用的是 `PHONE_LABELS` **完全相符**的標籤
比對，而且刻意寫得很窄 —— 理由是「模糊比對會抓到『緊急聯絡人電話』，
那支電話不是他的，卻打得開他的報名」。

**遮蔽不能照抄那條規則。** 兩者的失敗成本是反的：

| | 判太寬 | 判太窄 |
|---|---|---|
| 查詢 | **別人的電話打得開他的報名** | 他查不到（看得見，會反應） |
| 遮蔽 | 多遮一個不是電話的東西（看得見） | **一支電話就這樣攤在畫面上** |

所以查詢要窄，遮蔽要寬 —— 而「寬」在這裡是**看內容**，不是看標籤：

- 欄位可能叫「聯絡電話」「手機」「緊急聯絡人電話」「家長電話」
- **電話根本沒有自己的欄位型別**（`FIELD_TYPES` 裡沒有 phone），
  管理員是用「文字」建的，所以型別也認不出來
- 監護人那一格存的是「王小明／0912345678」—— 電話藏在字串中間

看內容一次全部蓋到，而且不必要求管理員改任何設定。

## ★ 只遮「看起來真的是電話」的

亂遮的代價是把不是電話的東西也蓋掉（金額、房號、人數）。所以：

- 要有**分機以外至少 8 碼數字**
- 要以 `0` 或 `+886` 開頭（台灣的號碼都是）
- 分隔符號（`-`、空白、括號）算在裡面，但不算長度

認不出來就**原樣回傳** —— 自作聰明切一個「看起來像遮蔽」的東西，
會讓人以為系統認得那個號碼（跟 `tw_id.mask` 同一條）。

## 留頭留尾

`0912345678` → `0912***678`。留得出「是不是我填的那支」，
但撿到畫面的人湊不出一個打得通的號碼。
"""
import re

#  一串電話：開頭 0 或 +886，中間可以有 - 空白 ( )，總數字量 8~11。
#  ★ 用 finditer 找**字串裡的**電話，不是整串比對 ——
#    監護人那一格是「王小明／0912345678」，整串比對會漏掉。
_PHONE = re.compile(r'(?:\+886|0)[\d\-\s()]{7,15}\d')

#  ★★ 台灣的號碼最短是 9 碼（區碼＋7 碼，例如 07-2345678）；
#    手機是 10 碼。設 9 是**真的下限**，不是隨手填的。
#
#    ★ 這個常數一度是死的：原本設 8，而 `HEAD + TAIL = 7` 本身就已經
#      讓 7 碼以下的東西遮不出任何星號 —— 也就是說把它改成 2 也沒有
#      任何行為變化。**一個看起來像防護、實際上什麼都沒擋的常數**，
#      跟先前刪掉的那支遮蔽死程式碼是同一個形狀。（mutation 抓到的。）
#
#    ★ 調到 9 順便修掉一個誤判：`07-09-2026`（8 碼、0 開頭、有分隔號）
#      原本會被當成電話遮掉。
MIN_DIGITS = 9
MAX_DIGITS = 12         # 含國碼；再長就不是電話了
HEAD, TAIL = 4, 3       # 留幾碼


def _mask_run(text):
    """把一串（已確認是電話的）文字裡的數字遮掉，保留原本的分隔符號。"""
    digits = [i for i, ch in enumerate(text) if ch.isdigit()]
    if len(digits) < MIN_DIGITS:
        return text
    hide = set(digits[HEAD:len(digits) - TAIL])
    #  ★ 不管遮掉幾碼，星號一律印固定的三個 —— 印成實際碼數的話，
    #    等於把「這支是幾碼」也一起講出去，而那對辨識沒有幫助。
    out, done = [], False
    for i, ch in enumerate(text):
        if i in hide:
            if not done:
                out.append('***')
                done = True
            continue
        out.append(ch)
    return ''.join(out)


def looks_like_phone(text):
    """這串文字是不是一支台灣的電話號碼。"""
    s = str(text or '').strip()
    if not s:
        return False
    m = _PHONE.fullmatch(s)
    if not m:
        return False
    n = sum(ch.isdigit() for ch in s)
    return MIN_DIGITS <= n <= MAX_DIGITS


def mask(value):
    """把字串裡的電話遮起來，其他部分原樣留著。

    ★ 認不出電話就**整串原樣回傳** —— 不要猜。
    """
    s = str(value or '')
    if not s:
        return ''

    def _sub(m):
        run = m.group(0)
        n = sum(ch.isdigit() for ch in run)
        if not (MIN_DIGITS <= n <= MAX_DIGITS):
            return run              # ★ 不是電話就不要動它
        return _mask_run(run)

    return _PHONE.sub(_sub, s)
